import numpy as np


# ============================================================
# 参数
# ============================================================

fs = 1000

# 每 0.1 秒计算一次 Topomap
topomap_time = 0.1

# 1000 Hz × 0.1 s = 100 个采样点
buffer_samples = int(fs * topomap_time)


# ============================================================
# 全局状态
# ============================================================

buffer = None

sample_count = 0

current_channels = None


# ============================================================
# 初始化
# ============================================================

def topomap_init(channels):

    global buffer
    global sample_count
    global current_channels

    current_channels = channels

    # 行 = 电极
    # 列 = 时间点
    #
    # 16导时：
    # buffer.shape = (16, 100)
    buffer = np.zeros(
        (channels, buffer_samples),
        dtype=np.float32
    )

    sample_count = 0

# ============================================================
# 计算 Topomap
# ============================================================

def calculate_topomap():

    # --------------------------------------------------------
    # 1. 每个电极计算平均功率
    #
    # P = mean(x²)
    #
    # buffer.shape = (channels, 100)
    # power.shape  = (channels,)
    # --------------------------------------------------------

    power = np.mean(buffer ** 2, axis=1)


    # --------------------------------------------------------
    # 2. 找最大功率电极
    #
    # 返回的是电极所在的行号
    #
    # 例如：
    # peak_index = 3
    # 表示第3行电极功率最大
    # --------------------------------------------------------

    peak_index = np.argmax(power)


    # --------------------------------------------------------
    # 3. 最大功率
    # --------------------------------------------------------

    peak_power = power[peak_index]


    # --------------------------------------------------------
    # 4. 全脑平均功率
    # --------------------------------------------------------

    global_mean_power = np.mean(power)


    # --------------------------------------------------------
    # 5. 组合返回结果
    #
    # 假设16导：
    #
    # result[0:16] = 16个电极功率
    # result[16]   = 峰值电极行号
    # result[17]   = 峰值功率
    # result[18]   = 全脑平均功率
    #
    # 总共19个数
    # --------------------------------------------------------

    result = np.concatenate([
        power,
        np.array([
            peak_index,
            peak_power,
            global_mean_power
        ])
    ])

    return result.astype(np.float32)


# ============================================================
# 实时 Topomap
# ============================================================

def realtime_topomap(current_data):

    global buffer
    global sample_count
    global current_channels


    # --------------------------------------------------------
    # C++传入：
    #
    # current_data.shape = (frames, channels)
    #
    # 例如一次3帧、16导：
    #
    # shape = (3, 16)
    #
    #           ch0 ch1 ch2 ... ch15
    # frame0     x   x   x       x
    # frame1     x   x   x       x
    # frame2     x   x   x       x
    # --------------------------------------------------------

    current_data = np.asarray(
        current_data,
        dtype=np.float32
    )


    # 当前数据有多少帧、多少通道
    frames = current_data.shape[0]
    channels = current_data.shape[1]


    # --------------------------------------------------------
    # 第一次运行，或者通道数量发生改变
    # --------------------------------------------------------

    if buffer is None or current_channels != channels:

        topomap_init(channels)


    # --------------------------------------------------------
    # 转置
    #
    # (frames, channels)
    #        ↓
    # (channels, frames)
    #
    # (3,16) → (16,3)
    # --------------------------------------------------------

    new_data = current_data.T


    # --------------------------------------------------------
    # 更新 buffer
    #
    # C++一次给3帧：
    #
    # buffer整体左移3列
    # --------------------------------------------------------

    buffer[:, :-frames] = buffer[:, frames:]


    # --------------------------------------------------------
    # 最后3列放入最新3帧
    # --------------------------------------------------------

    buffer[:, -frames:] = new_data


    # --------------------------------------------------------
    # 累计新进入多少帧
    # --------------------------------------------------------

    sample_count += frames


    # --------------------------------------------------------
    # 达到100个采样点
    #
    # fs = 1000 Hz
    # 100 samples = 100 ms
    # --------------------------------------------------------

    if sample_count >= buffer_samples:

        result = calculate_topomap()

        sample_count = 0

        return result


    # 没到100 ms，不计算
    return None